"""Rebuild js/tex-book.js + js/tex-book-2.js from images/art/*.jpg.

The 3D book (cover + pages) reads its artwork from this file (embedded WebP),
so it also works when index.html is opened straight from the folder (file://),
where browsers block WebGL from reading normal image files.

Needs Python 3 and Pillow:   pip install pillow
Run from the project folder: python tools/make-textures.py
Keep BOOK in step with "book.pages" / "book.cover" in js/main.js.
"""
import base64, io, json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# cover art first, then the pages (no trucks or maps: children's book spreads and comics first)
BOOK = ['children-06', 'children-01', 'comic-01', 'children-02', 'character-06', 'children-05', 'comic-05', 'children-03', 'sketch-04', 'children-04']
# Part 1 (needed for the first view: cover + first two spreads) loads with the page.
# Part 2 (later pages) is downloaded after start-up and painted in idle time.
FIRST = 3

def encode(name, size=1024, q=80):
    im = Image.open(os.path.join(ROOT, 'images', 'art', name + '.jpg')).convert('RGB')
    im.thumbnail((size, size), Image.LANCZOS)        # book pages: never above 760 px (the page picture is drawn at most ~560 px tall); service books: 480 px
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=q, method=6)
    return {'src': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(), 'w': im.width, 'h': im.height}

def write(fname, names, size=1024, q=80, var='WM_TEX'):
    data = {n: encode(n, size, q) for n in names}
    with open(os.path.join(ROOT, 'js', fname), 'w') as f:
        f.write('/* Book textures embedded as data URIs so WebGL works even from file://. Generated by tools/make-textures.py */\n')
        f.write('window.' + var + ' = Object.assign(window.' + var + ' || {}, ' + json.dumps(data) + ');\n')
    print('wrote js/' + fname)

write('tex-book.js', BOOK[:FIRST], 760)
write('tex-book-2.js', BOOK[FIRST:], 760)

# Service-card book (only "Book Cover Design" is drawn as a 3D book now): its cover + up to 3 of its artworks, small (400 px).
# Keep in step with SVC_BOOKS in js/main.js.
SVC = ['children-06']   # Book Cover Design card: cover art + its page (Waleed's own artwork)
write('tex-svc.js', SVC, 400, 70, 'WM_TEX_SVC')   # own namespace: never replaces the big hero-book pages
